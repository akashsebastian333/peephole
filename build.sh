#!/usr/bin/env bash
# Cross-compile the peephole binary for every supported platform and regenerate
# the integrity manifest. Run after changing any .go file or rules/*.json (rules
# are embedded into the binary). No external dependencies — Go stdlib only.
set -euo pipefail
cd "$(dirname "$0")"

# Regenerate the embedded KB as Go literals (with precomputed prefilters) so the
# hook pays no JSON/unmarshal/prefilter cost per event.
go run ./cmd/kbgen

targets="darwin/arm64 darwin/amd64 linux/amd64 linux/arm64 windows/amd64"
for t in $targets; do
  os=${t%/*}; arch=${t#*/}
  out="bin/peephole-$os-$arch"; [ "$os" = windows ] && out="$out.exe"
  # -buildvcs=false strips the vcs.revision/vcs.modified stamp so the binary is a
  # pure, reproducible function of the source (with -trimpath): a user can rebuild
  # and byte-match the committed artifact the integrity manifest pins.
  CGO_ENABLED=0 GOOS="$os" GOARCH="$arch" go build -trimpath -buildvcs=false -ldflags="-s -w" -o "$out" .
  echo "built $out"
done

# Manifest is generated by whichever native binary we can run here.
native="bin/peephole-$(uname -s | tr '[:upper:]' '[:lower:]')-$(uname -m | sed 's/x86_64/amd64/;s/aarch64/arm64/')"
if [ -x "$native" ]; then
  "$native" genmanifest
  "$native" selfcheck
else
  echo "warn: no native binary to generate manifest ($native)" >&2
fi
