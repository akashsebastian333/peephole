// Command kbgen generates rules_gen.go from rules/*.json: every rule with its
// patterns AND the precomputed literal prefilter set, as Go literals. This
// removes the per-invocation cost of reading 174 embedded JSON files,
// unmarshaling them, and computing 528 prefilters (~2ms of every hook event).
//
//	go run ./cmd/kbgen            # writes rules_gen.go (gofmt-clean)
//	go run ./cmd/kbgen --check    # exits 1 if rules_gen.go is stale (CI)
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"peephole/internal/litset"
)

type pattern struct {
	Lang       string `json:"lang"`
	Re         string `json:"re"`
	Confidence string `json:"confidence"`
	PrevNot    string `json:"prev_not,omitempty"`
	RejectRe   string `json:"reject_re,omitempty"`
	RequireRe  string `json:"require_re,omitempty"`
}

type rule struct {
	CWE            string    `json:"cwe_id"`
	Name           string    `json:"name"`
	Rank           int       `json:"rank"`
	KEV            bool      `json:"kev"`
	OWASP          []string  `json:"owasp,omitempty"`
	Severity       string    `json:"severity,omitempty"`
	TaskTriggers   []string  `json:"task_triggers"`
	Patterns       []pattern `json:"patterns"`
	Absence        []string  `json:"absence_requirements"`
	AttackScenario string    `json:"attack_scenario"`
	NegativeHints  []string  `json:"negative_test_hint"`
	Exemplar       struct {
		Noncompliant string `json:"noncompliant"`
		Compliant    string `json:"compliant"`
		Explanation  string `json:"explanation"`
	} `json:"exemplar"`
}

func strs(xs []string) string {
	if len(xs) == 0 {
		return "nil"
	}
	var b strings.Builder
	b.WriteString("{")
	for i, x := range xs {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(x))
	}
	b.WriteString("}")
	return "[]string" + b.String()
}

func emit() ([]byte, error) {
	entries, err := os.ReadDir("rules")
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".json") {
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)

	var b strings.Builder
	b.WriteString("// Code generated by cmd/kbgen from rules/*.json. DO NOT EDIT.\n\npackage main\n\nvar generatedRules = []Rule{\n")
	for _, name := range names {
		raw, err := os.ReadFile(filepath.Join("rules", name))
		if err != nil {
			return nil, err
		}
		var r rule
		if err := json.Unmarshal(raw, &r); err != nil {
			return nil, fmt.Errorf("%s: %w", name, err)
		}
		fmt.Fprintf(&b, "{\nCWE: %s,\nName: %s,\nRank: %d,\nKEV: %t,\n",
			strconv.Quote(r.CWE), strconv.Quote(r.Name), r.Rank, r.KEV)
		fmt.Fprintf(&b, "OWASP: %s,\nSeverity: %s,\n", strs(r.OWASP), strconv.Quote(r.Severity))
		fmt.Fprintf(&b, "TaskTriggers: %s,\n", strs(r.TaskTriggers))
		b.WriteString("Patterns: []Pattern{\n")
		for _, p := range r.Patterns {
			// prefilter set is computed HERE (build time), not per event
			pf := litset.Required(p.Re)
			fmt.Fprintf(&b, "{\nLang: %s,\nRe: %s,\nConfidence: %s,\n",
				strconv.Quote(p.Lang), strconv.Quote(p.Re), strconv.Quote(p.Confidence))
			if p.PrevNot != "" {
				fmt.Fprintf(&b, "PrevNot: %s,\n", strconv.Quote(p.PrevNot))
			}
			if p.RejectRe != "" {
				fmt.Fprintf(&b, "RejectRe: %s,\n", strconv.Quote(p.RejectRe))
			}
			if p.RequireRe != "" {
				fmt.Fprintf(&b, "RequireRe: %s,\n", strconv.Quote(p.RequireRe))
			}
			fmt.Fprintf(&b, "prefilter: %s,\n", strs(pf))
			b.WriteString("},\n")
		}
		b.WriteString("},\n")
		fmt.Fprintf(&b, "Absence: %s,\n", strs(r.Absence))
		fmt.Fprintf(&b, "AttackScenario: %s,\n", strconv.Quote(r.AttackScenario))
		fmt.Fprintf(&b, "NegativeHints: %s,\n", strs(r.NegativeHints))
		b.WriteString("Exemplar: struct {\nNoncompliant string `json:\"noncompliant\"`\nCompliant string `json:\"compliant\"`\nExplanation string `json:\"explanation\"`\n}{\n")
		fmt.Fprintf(&b, "Noncompliant: %s,\nCompliant: %s,\nExplanation: %s,\n},\n",
			strconv.Quote(r.Exemplar.Noncompliant), strconv.Quote(r.Exemplar.Compliant), strconv.Quote(r.Exemplar.Explanation))
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return format.Source([]byte(b.String()))
}

func main() {
	out, err := emit()
	if err != nil {
		fmt.Fprintln(os.Stderr, "kbgen:", err)
		os.Exit(1)
	}
	if len(os.Args) > 1 && os.Args[1] == "--check" {
		cur, err := os.ReadFile("rules_gen.go")
		if err != nil || !bytes.Equal(bytes.TrimSpace(cur), bytes.TrimSpace(out)) {
			fmt.Fprintln(os.Stderr, "rules_gen.go is stale - run: go run ./cmd/kbgen && ./build.sh")
			os.Exit(1)
		}
		fmt.Println("rules_gen.go up to date")
		return
	}
	tmp := "rules_gen.go.tmp"
	if err := os.WriteFile(tmp, out, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "kbgen:", err)
		os.Exit(1)
	}
	if err := exec.Command("gofmt", "-w", tmp).Run(); err == nil {
		out2, _ := os.ReadFile(tmp)
		out = out2
	}
	if err := os.Rename(tmp, "rules_gen.go"); err != nil {
		fmt.Fprintln(os.Stderr, "kbgen:", err)
		os.Exit(1)
	}
	fmt.Println("rules_gen.go written:", len(out), "bytes")
}
